// Geometry is measured once in PSD coordinates and emitted as section-local percentages.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const mapPath = path.join(root, 'docs/landing-spc-layout.json');
const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
const percent = (value, total) => Number((value / total * 100).toFixed(6));
// Pixel coordinates are the editable source; percentages are always derived.
for (const section of map.sections) {
  section.topPercent = percent(section.y, map.canvas.height);
  section.heightPercent = percent(section.height, map.canvas.height);
}
for (const element of map.elements) {
  const section = map.sections.find(item => item.id === element.section);
  if (!section) throw new Error(`Unknown section for ${element.id}: ${element.section}`);
  const box = element.box;
  element.percent = {
    left: percent(box.x - section.x, section.width),
    top: percent(box.y - section.y, section.height),
    width: percent(box.width, section.width),
    height: percent(box.height, section.height)
  };
  element.pagePercent = {
    left: percent(box.x, map.canvas.width),
    top: percent(box.y, map.canvas.height),
    width: percent(box.width, map.canvas.width),
    height: percent(box.height, map.canvas.height)
  };
}
fs.writeFileSync(mapPath, JSON.stringify(map, null, 2) + '\n');
const css = ['/* Generated by scripts/generate_spc_layout.cjs. Edit docs/landing-spc-layout.json. */',
  '@media (min-width:701px) {'];
for (const section of map.sections) {
  css.push(`  .spc-page ${section.selector}{aspect-ratio:${section.width}/${section.height};margin-top:calc(${section.overlap} * var(--spc-unit))}`);
}
for (const element of map.elements) {
  const p = element.percent;
  css.push(`  /* ${element.id} */\n  .spc-page ${element.selector}{position:absolute;inset:auto;left:${p.left}%;top:${p.top}%;width:${p.width}%;height:${p.height}%!important;min-height:0;max-width:none;margin:0!important;padding:0;transform:none}`);
}
css.push('}', '');
fs.writeFileSync(path.join(root, 'assets/landing-piso-spc-layout.css'), css.join('\n'));
console.log(`SPC: ${map.sections.length} sections, ${map.elements.length} anchors generated.`);
